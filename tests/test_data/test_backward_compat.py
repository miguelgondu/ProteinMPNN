if TYPE_CHECKING:
    from pathlib import Path

# Paths relative to repo root
FIXTURES_DIR = ROOT_DIR / "tests" / "fixtures"
DATA_DIR = ROOT_DIR / "data" / "pdbs"
EXAMPLES_DIR = ROOT_DIR / "examples"


class TestSingleStateBackwardCompat:
    """Test backward compatibility for single-state design."""

    @pytest.fixture
    def old_output(self) -> dict:
        """Load the fixture generated by old code."""
        fixture_path = FIXTURES_DIR / "6MRR_A1-A68_old.json"
        if not fixture_path.exists():
            pytest.skip(f"Fixture not found: {fixture_path}")
        with fixture_path.open() as f:
            return json.load(f)

    @pytest.fixture
    def new_output(self) -> dict:
        """Generate output using new code."""
        pdb_path = DATA_DIR / "6MRR.pdb"
        if not pdb_path.exists():
            pytest.skip(f"PDB not found: {pdb_path}")

        design = SingleStateDesignInput(
            pdb_path=pdb_path,
            designable_res="A1-A68",
        )
        config = design.to_config()
        return json.loads(config.model_dump_json())

    def test_designable_residues_match_exactly(
        self, old_output: dict, new_output: dict
    ) -> None:
        """Verify designable residues match exactly between old and new code."""
        assert len(old_output["designable"]) == len(new_output["designable"])

        for old_res, new_res in zip(old_output["designable"], new_output["designable"]):
            assert old_res["chain"] == new_res["chain"]
            assert old_res["resid"] == new_res["resid"]
            assert old_res["WTAA"] == new_res["WTAA"]
            assert old_res["MutTo"] == new_res["MutTo"]

    def test_symmetric_groups_match(self, old_output: dict, new_output: dict) -> None:
        """Verify symmetric groups match between old and new code."""
        assert old_output["symmetric"] == new_output["symmetric"]

    def test_amino_acid_portion_matches(
        self, old_output: dict, new_output: dict
    ) -> None:
        """Verify the amino acid (non-X) portion of sequences match.

        Both old and new code should produce the same amino acids for real
        residues. The difference is only in how gaps/unknown residues are
        represented.
        """
        for chain_id in old_output["sequence"]:
            old_seq = old_output["sequence"][chain_id]
            new_seq = new_output["sequence"][chain_id]

            # Extract non-X characters (real amino acids)
            old_aas = "".join(c for c in old_seq if c != "X")
            new_aas = "".join(c for c in new_seq if c != "X")

            assert old_aas == new_aas, (
                f"Chain {chain_id} amino acids differ:\nOld: {old_aas}\nNew: {new_aas}"
            )

    def test_old_sequence_is_longer_due_to_xxx_bug(
        self, old_output: dict, new_output: dict
    ) -> None:
        """Document the XXX bug causes longer sequences in old code.

        The old code has a bug where unknown residues (like HOH/water) are
        encoded as 'XXX' (3 chars) instead of 'X' (1 char). This causes the
        old sequence to be longer than the new one.
        """
        old_seq = old_output["sequence"]["A"]
        new_seq = new_output["sequence"]["A"]

        # Old sequence should be longer due to the bug
        assert len(old_seq) > len(new_seq), (
            f"Expected old sequence ({len(old_seq)}) to be longer than "
            f"new sequence ({len(new_seq)}) due to XXX bug"
        )

        # Old code: each water adds 3 X's, new code: each water adds 1 X
        # Plus both have the same gaps (32 in this case)
        # So: old_x_count = 3 * waters + gaps, new_x_count = waters + gaps
        # Difference in length = 2 * waters
        length_diff = len(old_seq) - len(new_seq)
        assert length_diff > 0, "Old sequence should be longer"

    def test_new_sequence_length_is_correct(self, new_output: dict) -> None:
        """Verify new sequence length matches expected PDB structure.

        For 6MRR, residues are numbered 1-216, so sequence should be 216 chars.
        """
        new_seq = new_output["sequence"]["A"]
        # PDB has residue numbers 1-216
        assert len(new_seq) == 216, f"Expected sequence length 216, got {len(new_seq)}"

    def test_chain_ids_match(self, old_output: dict, new_output: dict) -> None:
        """Verify the same chains are present in both outputs."""
        assert set(old_output["sequence"].keys()) == set(new_output["sequence"].keys())


