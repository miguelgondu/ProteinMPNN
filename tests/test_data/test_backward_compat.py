"""Tests for backward compatibility with old generate_json.py output.

These tests verify that the new SingleStateDesignInput and MultiStateDesignInput
classes produce output equivalent to the old ProteinDesignInputFormatter from
run/generate_json.py.

Note: The old code has a bug where unknown residue types (like water/HOH) are
mapped to 'XXX' (3 characters) instead of 'X' (1 character), causing sequence
lengths to differ. The new code fixes this bug. These tests verify that the
critical fields (designable, symmetric) match exactly, while accounting for
the sequence length difference.
"""

