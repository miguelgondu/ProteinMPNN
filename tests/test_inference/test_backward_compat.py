"""Backward compatibility tests for inference module.

These tests verify that the new InferenceRunner produces output consistent
with the original run_protein_mpnn.py implementation.

There are two types of tests:
1. TestInferenceMatchesOriginal - Compares new code against the ORIGINAL code in run/
   The fixture was generated using scripts/generate_original_fixtures.py
2. TestInferenceRegression - Ensures the new code is deterministic and doesn't change
   The fixture captures the new code's current behavior for regression testing
"""

from __future__ import annotations

import json

import pytest

from proteinmpnn.inference import InferenceRunner
from proteinmpnn.utils.constants import ROOT_DIR, WEIGHTS_PATH

# Test data paths
DATA_DIR = ROOT_DIR / "data" / "pdbs"
EXAMPLES_DIR = ROOT_DIR / "examples"
FIXTURES_DIR = ROOT_DIR / "tests" / "fixtures"


def weights_available() -> bool:
    """Check if model weights are available."""
    return (WEIGHTS_PATH / "v_48_020.pt").exists()


@pytest.mark.skipif(not weights_available(), reason="Model weights not available")
class TestInferenceMatchesOriginal:
    """Test that new inference EXACTLY matches the ORIGINAL run_protein_mpnn.py output.

    The fixture was generated by running the original code in run/ directory
    using scripts/generate_original_fixtures.py. This ensures we compare against
    the true original behavior, not against outputs generated by the new code.

    When properly seeded, both implementations produce IDENTICAL results, confirming
    that the new code is a faithful reimplementation of the original.
    """

    @pytest.fixture
    def original_output(self) -> dict:
        """Load fixture generated from ORIGINAL code in run/."""
        fixture_path = FIXTURES_DIR / "6MRR_inference_original.json"
        if not fixture_path.exists():
            pytest.skip(f"Fixture not found: {fixture_path}")
        with fixture_path.open() as f:
            return json.load(f)

    @pytest.fixture
    def new_output(self) -> dict:
        """Generate output using new InferenceRunner."""
        import torch

        pdb_path = DATA_DIR / "6MRR.pdb"
        if not pdb_path.exists():
            pytest.skip(f"PDB not found: {pdb_path}")

        # Force CPU to ensure cross-platform reproducibility
        # (torch.randn produces different values on
        # different devices even with same seed)
        runner = InferenceRunner(model_name="v_48_020", device=torch.device("cpu"))
        result = runner.design_single(
            pdb_path=pdb_path,
            designable_res="A1-A68",
            num_sequences=3,
            seed=42,
        )
        return {
            "native": {
                "name": result.native.name,
                "score": result.native.score,
                "fixed_chains": result.native.fixed_chains,
                "designed_chains": result.native.designed_chains,
                "model_name": result.native.model_name,
                "sequence": result.native.sequence,
            },
            "sequences": [
                {
                    "temperature": s.temperature,
                    "sample_index": s.sample_index,
                    "score": s.score,
                    "seq_recovery": s.seq_recovery,
                    "sequence": s.sequence,
                }
                for s in result.sequences
            ],
        }

    def test_native_sequence_matches_exactly(
        self, original_output: dict, new_output: dict
    ) -> None:
        """Native sequence must match exactly."""
        assert original_output["native"]["sequence"] == new_output["native"]["sequence"]

    def test_native_score_matches_exactly(
        self, original_output: dict, new_output: dict
    ) -> None:
        """Native score must match within tight tolerance."""
        old_score = original_output["native"]["score"]
        new_score = new_output["native"]["score"]
        assert abs(old_score - new_score) < 1e-4, (
            f"Native scores differ: original={old_score}, new={new_score}"
        )

    def test_native_metadata_matches(
        self, original_output: dict, new_output: dict
    ) -> None:
        """Native metadata (name, chains, model) must match."""
        assert original_output["native"]["name"] == new_output["native"]["name"]
        assert (
            original_output["native"]["fixed_chains"]
            == new_output["native"]["fixed_chains"]
        )
        assert (
            original_output["native"]["designed_chains"]
            == new_output["native"]["designed_chains"]
        )
        assert (
            original_output["native"]["model_name"]
            == new_output["native"]["model_name"]
        )

    def test_designed_sequences_match_exactly(
        self, original_output: dict, new_output: dict
    ) -> None:
        """Designed sequences must match exactly (same seed = deterministic)."""
        assert len(original_output["sequences"]) == len(new_output["sequences"])

        for i, (orig_seq, new_seq) in enumerate(
            zip(original_output["sequences"], new_output["sequences"])
        ):
            assert orig_seq["sequence"] == new_seq["sequence"], (
                f"Sequence {i} differs:\n"
                f"  Original: {orig_seq['sequence']}\n"
                f"  New: {new_seq['sequence']}"
            )

    def test_designed_scores_match(
        self, original_output: dict, new_output: dict
    ) -> None:
        """Designed scores must match within tolerance."""
        for i, (orig_seq, new_seq) in enumerate(
            zip(original_output["sequences"], new_output["sequences"])
        ):
            assert abs(orig_seq["score"] - new_seq["score"]) < 1e-4, (
                f"Score {i} differs: original={orig_seq['score']}, "
                f"new={new_seq['score']}"
            )

    def test_seq_recovery_matches(
        self, original_output: dict, new_output: dict
    ) -> None:
        """Sequence recovery must match within tolerance."""
        for i, (orig_seq, new_seq) in enumerate(
            zip(original_output["sequences"], new_output["sequences"])
        ):
            assert abs(orig_seq["seq_recovery"] - new_seq["seq_recovery"]) < 1e-4, (
                f"Seq recovery {i} differs: "
                f"original={orig_seq['seq_recovery']}, "
                f"new={new_seq['seq_recovery']}"
            )


